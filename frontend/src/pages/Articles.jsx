import { useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { getAllNews } from "../api/newsApi";
import { getErrorMessage } from "../api/api";
import { formatRelativeTime, normalizeArticle } from "../utils/article";
import ArticleCard from "../components/ArticleCard";
import Loader from "../components/Loader";

function sortByNewest(list) {
  return [...list].sort((a, b) => {
    const aTime = new Date(a.published_at || 0).getTime();
    const bTime = new Date(b.published_at || 0).getTime();
    return bTime - aTime;
  });
}

function buildTopicStats(list) {
  const counts = new Map();
  list.forEach((article) => {
    (article.keywords || []).forEach((word) => {
      const key = String(word || "").trim();
      if (!key) return;
      counts.set(key, (counts.get(key) || 0) + 1);
    });
  });
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 8)
    .map(([label, count]) => ({ label, count }));
}

function matchesQuery(article, query) {
  if (!query) return true;
  const haystack = [
    article.title,
    article.summary,
    article.source,
    article.category,
    ...(article.keywords || []),
  ]
    .join(" ")
    .toLowerCase();
  return haystack.includes(query.toLowerCase());
}

function ArticleCta({ article, className = "btn-primary", children }) {
  if (article.live && article.href) {
    return (
      <a
        href={article.href}
        target="_blank"
        rel="noopener noreferrer"
        className={className}
      >
        {children}
      </a>
    );
  }

  return (
    <Link to={`/articles/${article._id}`} className={className}>
      {children}
    </Link>
  );
}

export default function Articles() {
  const [articles, setArticles] = useState([]);
  const [keyword, setKeyword] = useState("");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    let cancelled = false;

    const load = async () => {
      setLoading(true);
      setError("");

      try {
        const generated = await getAllNews();

        if (cancelled) return;

        const generatedArticles = sortByNewest(
          (Array.isArray(generated) ? generated : []).map(normalizeArticle)
        );
        setArticles(generatedArticles);

        if (generatedArticles.length === 0) {
          setError("No articles available right now.");
        }
      } catch (err) {
        if (!cancelled) {
          setArticles([]);
          setError(getErrorMessage(err, "Failed to load AI articles"));
        }
      } finally {
        if (!cancelled) setLoading(false);
      }
    };

    load();
    return () => {
      cancelled = true;
    };
  }, []);

  const filteredArticles = useMemo(
    () => articles.filter((article) => matchesQuery(article, keyword.trim())),
    [articles, keyword]
  );
  const topics = useMemo(() => buildTopicStats(articles), [articles]);
  const cover = filteredArticles[0] || null;
  const spotlight = filteredArticles.slice(1, 3);
  const catalog = filteredArticles.slice(3);

  const applyTopic = (topic) => {
    setKeyword((prev) => (prev.toLowerCase() === topic.toLowerCase() ? "" : topic));
  };

  if (loading && articles.length === 0) {
    return <Loader label="Loading generated articles..." />;
  }

  return (
    <div className="page articles-page">
      <header className="articles-hero-bar">
        <div className="articles-hero-bar-inner">
          <div>
            <p className="articles-eyebrow">Generated library</p>
            <h1>AI Articles</h1>
            <p className="articles-intro">
              AI coverage generated by our newsroom pipeline, organized as a cover story,
              spotlights, and a full reading list.
            </p>
          </div>
        </div>
      </header>

      <div className="articles-body">
        <div className="articles-filter-bar">
          <input
            type="search"
            value={keyword}
            onChange={(event) => setKeyword(event.target.value)}
            placeholder="Filter generated articles..."
          />
          <div className="articles-topic-rail">
            {topics.map((topic) => (
              <button
                key={topic.label}
                type="button"
                className={`articles-topic ${
                  keyword.toLowerCase() === topic.label.toLowerCase() ? "active" : ""
                }`}
                onClick={() => applyTopic(topic.label)}
              >
                {topic.label}
              </button>
            ))}
            {keyword ? (
              <button type="button" className="articles-topic clear" onClick={() => setKeyword("")}>
                Clear
              </button>
            ) : null}
          </div>
        </div>

        {error ? <div className="alert alert-error">{error}</div> : null}

        {filteredArticles.length === 0 ? (
          <div className="empty-state">
            <h2>{articles.length === 0 ? "No generated articles yet" : "No matches"}</h2>
            <p>
              {articles.length === 0
                ? "Generated coverage is unavailable right now. Try again shortly."
                : `Nothing matched “${keyword}”. Try another topic.`}
            </p>
          </div>
        ) : null}

        {cover ? (
          <section className="articles-cover">
            <div className="articles-cover-index">01</div>
            <div className="articles-cover-copy">
              <div className="story-meta">
                <span className="badge">Cover story</span>
                <span className="meta-text">{cover.source}</span>
                <span className="meta-text">{formatRelativeTime(cover.published_at)}</span>
              </div>
              <h2>{cover.title}</h2>
              <p>{cover.summary}</p>
              {cover.keywords?.length ? (
                <div className="tag-row">
                  {cover.keywords.slice(0, 4).map((word) => (
                    <button
                      key={word}
                      type="button"
                      className="tag topic-tag-btn"
                      onClick={() => applyTopic(word)}
                    >
                      #{word}
                    </button>
                  ))}
                </div>
              ) : null}
              <ArticleCta article={cover}>Read full article →</ArticleCta>
            </div>
          </section>
        ) : null}

        {spotlight.length > 0 ? (
          <section className="articles-spotlight">
            {spotlight.map((article, index) => (
              <ArticleCta
                key={article._id}
                article={article}
                className="articles-spotlight-card"
              >
                <span className="articles-spotlight-num">0{index + 2}</span>
                <div className="story-meta">
                  <span className="badge">Spotlight</span>
                  <span className="meta-text">{article.source}</span>
                  <span className="meta-text">{formatRelativeTime(article.published_at)}</span>
                </div>
                <h3>{article.title}</h3>
                <p>{article.summary}</p>
                <span className="text-link">Continue reading →</span>
              </ArticleCta>
            ))}
          </section>
        ) : null}

        {catalog.length > 0 ? (
          <section className="articles-catalog">
            <div className="articles-catalog-head">
              <h2>Catalog</h2>
              <span>{catalog.length} generated pieces</span>
            </div>
            <div className="articles-catalog-grid">
              {catalog.map((article, index) => (
                <ArticleCard
                  key={article._id}
                  article={article}
                  index={index + 4}
                  onTopicClick={applyTopic}
                />
              ))}
            </div>
          </section>
        ) : null}

      </div>
    </div>
  );
}
